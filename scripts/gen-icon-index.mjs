#!/usr/bin/env node
/**
 * Generate src/app/data/cocIconIndex.ts — the set of Clash of Clans icon paths
 * that actually exist in public/images/coc.
 *
 * The army view resolves an icon by trying candidate filenames in order. It
 * used to do that by creating an Image() per candidate and waiting for onerror,
 * so a name that only matches on the fourth try cost three wasted round trips —
 * and in production a miss is not even a 404, it is the SPA fallback returning
 * index.html with status 200. With this index the same candidate list resolves
 * synchronously, with zero requests for the misses.
 *
 * Run after scripts/optimize-images.mjs; committed so the build stays offline.
 */
import { readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const COC = path.join(ROOT, 'public', 'images', 'coc');
const OUT = path.join(ROOT, 'src', 'app', 'data', 'cocIconIndex.ts');

async function* walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(full);
    else yield full;
  }
}

const paths = [];
for await (const file of walk(COC)) {
  paths.push('/images/coc/' + path.relative(COC, file).split(path.sep).join('/'));
}
paths.sort();

const body = `// GENERATED by scripts/gen-icon-index.mjs — do not edit by hand.
// Every Clash of Clans icon present in public/images/coc, so a candidate path
// can be resolved with a lookup instead of a network probe.

const PATHS = new Set<string>([
${paths.map((p) => `  '${p}',`).join('\n')}
]);

/**
 * First candidate that exists on disk, or undefined.
 * Candidates may still be written with a .png extension: the art pipeline
 * emits WebP, so the extension is normalised here rather than at every call site.
 */
export function resolveCocIcon(candidates: string[]): string | undefined {
  for (const candidate of candidates) {
    const webp = candidate.replace(/\\.png$/i, '.webp');
    if (PATHS.has(webp)) return webp;
    if (PATHS.has(candidate)) return candidate;
  }
  return undefined;
}
`;

await writeFile(OUT, body);
console.log(`icon index: ${paths.length} paths → src/app/data/cocIconIndex.ts`);
